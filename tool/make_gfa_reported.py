#!/usr/bin/env python3
"""Owner-reported gross floor area for existing Vancouver buildings (sweep M66; J.B. 18 Oct 2026).
Source: City of Vancouver GHG limits by-law reporting map, Export data → Disclosed Data (exported 18 Oct 2026; reporting year 2025; buildings whose owners
agreed to disclose: commercial ≥ 50,000 ft², multi-family and hotels ≥ 100,000 ft²). data/raw/van/energy_report/disclosed_2025_extract.csv.
Matched to tool parcels by civic number + street name + direction (a direction missing on one side is allowed when that leaves one match; W never matches E).
All parcels sharing the address are taken together (strata and air-space parcels). Not used where the reported area exceeds 1.2 × a generous building-part estimate for those parcels (3 m storeys): the report then covers more than this lot's buildings
(e.g. 900 W Hastings: 12,422 m² against a 289 m² lot). Out: gfa_van.js (BD.GFA_REP keyed by parcel id)."""
import json, glob, os, re, csv
from shapely.geometry import Polygon
from shapely.strtree import STRtree
H = os.path.dirname(os.path.abspath(__file__)); Q = 2; T = 1500
def dec(r, ox, oy):
    pts = []; x = y = None
    for i in range(0, len(r), 2):
        if x is None: x, y = r[i], r[i + 1]
        else: x += r[i]; y += r[i + 1]
        pts.append((ox + x / Q, oy + y / Q))
    return pts
B = []; P = []; A = {}
for f in glob.glob(os.path.join(H, 'tiles', 'van', 't_*.json')):
    i, j = map(int, os.path.basename(f)[2:-5].split('_')); d = json.load(open(f))
    for b in d.get('B', []):
        p = dec(b[1], i * T, j * T)
        if len(p) >= 3:
            g = Polygon(p)
            if g.is_valid and g.area > 20: B.append((g, b[0]))
    ox, oy = d['o']
    for e in d.get('P', []):
        p = dec(e[1], ox, oy)
        if len(p) >= 3:
            g = Polygon(p)
            if g.is_valid and g.area > 50: P.append((e[0], g))
    A.update(d.get('A', {}))
tree = STRtree([b[0] for b in B])
def k_tax(a):
    t = a.upper().split()
    if not t or not t[0].isdigit(): return None
    d = t[-1] if t[-1] in ('W', 'E', 'N', 'S') else ''
    rest = [x for x in t[1:] if x not in ('W', 'E', 'N', 'S')]
    return (t[0], rest[0] if rest else '', d)
def k_rep(s):
    t = s.upper().replace(',', '').split()
    if not t or not re.match(r'^\d+', t[0]): return None
    num = re.match(r'^\d+', t[0]).group(0); d = ''; rest = t[1:]
    if rest and rest[0] in ('W', 'E', 'N', 'S'): d = rest[0]; rest = rest[1:]
    return (num, rest[0] if rest else '', d)
rep = {}
for r in csv.DictReader(open(os.path.join(H, '..', 'data', 'raw', 'van', 'energy_report', 'disclosed_2025_extract.csv'))):
    k = k_rep(r['Steet'])
    if k: rep.setdefault(k, []).append(r)
out = {}; skipped = []
from shapely.ops import unary_union
groups = {}
for pid, g in P:
    a = A.get(pid, [''])[0]
    if a: groups.setdefault(a, []).append((pid, g))
for a, ps in groups.items():
    k = k_tax(a)
    if not k: continue
    m = rep.get(k)
    if not m:
        c = [r for kk, v in rep.items() if kk[0] == k[0] and kk[1] == k[1] and (not kk[2] or not k[2]) for r in v]  # a missing direction on one side only; never W for E
        m = c if len(c) == 1 else None
    if not m: continue
    r = m[0]; gfa = round(float(r['Reported Gross Floor Area (m2)']))
    U = unary_union([g for _, g in ps]).buffer(0.5)  # every parcel with this address (strata and air-space parcels share one)
    bs = {int(x): B[int(x)] for x in tree.query(U) if U.contains(B[int(x)][0].representative_point())}
    per = sum(b[0].area * max(1, int(b[1] // 4)) for b in bs.values() if b[1] and b[1] > 0)
    per3 = sum(b[0].area * max(1, int(b[1] // 3)) for b in bs.values() if b[1] and b[1] > 0)  # 3 m storeys (homes) as the generous bound
    if not per or gfa > 1.2 * per3: skipped.append((a, gfa, round(per))); continue
    hei = r['Annual Heat Energy Intensity (GJ/m2) (Annual HEI)']
    for pid, _ in ps:
        out[pid] = dict(gfa=gfa, id=r['Building ID'], use=r['Primary Use Type (ESPM Calculated)'], hei=float(hei) if re.match(r'^[\d.]+$', hei) else None, n=len(ps), est=round(per))
open(os.path.join(H, 'gfa_van.js'), 'w').write('/* generated by make_gfa_reported.py — owner-reported gross floor area, City of Vancouver reporting map (Disclosed Data, reporting year 2025, exported 18 Oct 2026), keyed by parcel id */\nwindow.BD=window.BD||{}; BD.GFA_REP=' + json.dumps(out, separators=(',', ':')) + ';\n')
print('parcels with reported GFA', len(out), '| report buildings used', len({v['id'] for v in out.values()}), '| skipped (report larger than the lot\'s buildings)', len(skipped))
for s in skipped[:12]: print('  skip', s)
