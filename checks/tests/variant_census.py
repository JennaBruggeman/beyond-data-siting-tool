# Variant census (J.B. 12 Nov 2026, item 1c): for every lot where a data centre is allowed, the layout the hub engine would need that it doesn't have yet.
# Same rules as tool/hub.js variantNeed() (keep the two in step). Lot measures from checks/lot_types_2026-11-07.csv (job A1, ids and measures only).
# Rules are our reading of the 13 frozen boards (EH-FREEZE-2026-11-11g), first that applies:
#   Vancouver (stacked): buildable < 1,100 m² or type small -> small-lot (generators or chillers upstairs: 1360, 1330)
#                        wide_shallow -> full frontage, plant at the rear (1353) · irregular -> placed where the lot is wide (8980)
#                        width < 20 m (narrow lots, through lots with no front) -> two hall storeys with the roof-chiller stop (8238)
#                        otherwise the engine's own layout (339's type: regular, large, narrow_deep at least 20 m wide)
#   Edmonton (beside, at grade): every lot -> hall grown into the plant yard (the 11g at-grade rule: 4103, 10003, 15231, 16075); and by type
#                        small -> small-lot (10004) · wide_shallow -> turned beside (16075) · narrow_deep -> narrow-deep beside (15231) · irregular -> placed where wide (10003)
#   "Plant on the roof as drawn" (06B, 14715) is a drawing choice on two boards, not a lot type: not counted.
# Allowed lots: Vancouver = every row (the CSV lists the zones where a data centre is conditional, I-3 sub-area B left out);
#   Edmonton = IH and EETC rows (Major Industrial permitted; the 386 of the tool's count).
# Usage: python variant_census.py [out.md]
import csv, sys, os, collections
here = os.path.dirname(os.path.abspath(__file__))
rows = list(csv.DictReader(open(os.path.join(here, '..', 'lot_types_2026-11-07.csv'), encoding='utf-8')))
NAMES = {'small': 'small lot: generators or chillers upstairs', 'rearplant': 'full frontage, plant at the rear', 'wide': 'placed where the lot is wide',
         'twohall': 'two hall storeys with the roof-chiller stop', 'growyard': 'hall grown into the plant yard (at grade)', 'turned': 'turned beside', 'narrowdeep': 'narrow-deep beside'}
def need(r):
    t, b, w = r['type'], float(r['buildable_m2'] or 0), float(r['width_m'] or 0)
    if r['city'] == 'van':
        if t == 'small' or b < 1100: return ['small']
        if t == 'wide_shallow': return ['rearplant']
        if t == 'irregular': return ['wide']
        if w < 20: return ['twohall']
        return []
    out = ['growyard']
    if t == 'small' or b < 853: out.append('small')
    elif t == 'wide_shallow': out.append('turned')
    elif t == 'narrow_deep': out.append('narrowdeep')
    elif t == 'irregular': out.append('wide')
    return out
res = {}; need_out = {'van': {}, 'edm': {}}
for city, keep in (('van', lambda r: r['city'] == 'van'), ('edm', lambda r: r['city'] == 'edm' and r['zone'] in ('IH', 'EETC'))):
    L = [r for r in rows if keep(r)]; c = collections.Counter(); prim = collections.Counter(); none = 0
    for r in L:
        n = need(r)
        if n: need_out[city][r['key']] = n
        if not n: none += 1
        for k in n: c[k] += 1
        prim[n[-1] if n else 'engine'] += 1
    res[city] = (len(L), none, c, prim)
lines = ['# Variant census, 12 Nov 2026 (checks/tests/variant_census.py)', '', 'Lots where a data centre is allowed, and the layout the hub engine would need that it does not have yet. Rules: our reading of the 13 frozen boards (EH-FREEZE-2026-11-11g); see the script header. A lot can need two (Edmonton: the at-grade growth rule, and a layout by lot type).', '']
for city, (n, none, c, prim) in res.items():
    lines.append(f'## {"Vancouver" if city == "van" else "Edmonton"}: {n} lots')
    lines.append(''); lines.append('| Layout needed | Lots | Share |'); lines.append('|---|---|---|')
    lines.append(f'| none: the engine’s own layout | {none} | {100 * none / n:.0f} % |')
    for k, v in c.most_common(): lines.append(f'| {NAMES[k]} | {v} | {100 * v / n:.0f} % |')
    lines.append('')
open(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, '..', 'variant_census_2026-11-12.md'), 'w', encoding='utf-8').write('\n'.join(lines))
print('\n'.join(lines))

